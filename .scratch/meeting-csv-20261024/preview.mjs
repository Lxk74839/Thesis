import fs from 'node:fs/promises';
import {Workbook} from '@oai/artifact-tool';
const root='D:/Work/Codex/Project/Thesis';
const csv=await fs.readFile(root+'/reports/组会汇报与100用户数据_20261024/100用户CSV数据集/02_历史评论.csv','utf8');
const wb=await Workbook.fromCSV(csv,{sheetName:'历史评论'});
const original=wb.worksheets.getItem('历史评论').getRange('A1:L4').values;
const preview=wb.worksheets.add('CSV数据预览');
const matrix=[['用户编号','商品标识','作物类型','评分','评论节选 前90字符'],...original.slice(1).map(r=>[r[0],r[3],r[4],r[6],String(r[9]).slice(0,90)])];
preview.getRange('A1:E4').values=matrix;
preview.showGridLines=true;
preview.getRange('A1:E4').format.font={name:'Microsoft YaHei',size:14,color:'#17202A'};
preview.getRange('A1:E4').format.verticalAlignment='center';
preview.getRange('A1:E4').format.wrapText=true;
preview.getRange('A1:E1').format.fill='#244865';
preview.getRange('A1:E1').format.font={name:'Microsoft YaHei',size:14,bold:true,color:'#FFFFFF'};
for(const [col,width] of [['A',85],['B',150],['C',90],['D',60],['E',470]]) preview.getRange(col+'1:'+col+'4').format.columnWidthPx=width;
preview.getRange('A1:E1').format.rowHeightPx=40;
preview.getRange('A2:E4').format.rowHeightPx=78;
preview.getRange('A2:E4').format.fill='#FFFFFF';
preview.getRange('A1:E4').format.borders={preset:'all',style:'thin',color:'#D7DFE5'};
wb.recalculate();
const image=await wb.render({sheetName:'CSV数据预览',range:'A1:E4',scale:1.8,format:'png'});
await fs.writeFile(root+'/.scratch/meeting-csv-20261024/csv-preview.png',new Uint8Array(await image.arrayBuffer()));
await fs.writeFile(root+'/.scratch/meeting-csv-20261024/csv-preview-values.json',JSON.stringify({source:'02_历史评论.csv',rows:matrix,comment_prefix_characters:90}));
console.log(JSON.stringify({preview_rows:matrix.length-1,columns:matrix[0],output:'csv-preview.png'}));